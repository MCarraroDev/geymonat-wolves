/**
 * Ottiene un articolo per slug
 */
export const getArticleBySlug = (slug) => {
  return articles.find(article => article.slug === slug)
}

/**
 * Ottiene un articolo per ID
 */
export const getArticleById = (id) => {
  return articles.find(article => article.id === parseInt(id))
}

/**
 * Ottiene tutti gli articoli ordinati per data (più recenti prima)
 */
export const getArticlesByDate = () => {
  return [...articles].sort((a, b) => new Date(b.date) - new Date(a.date))
}

/**
 * Ottiene articoli per tag
 */
export const getArticlesByTag = (tag) => {
  return articles.filter(article => article.tags.includes(tag))
}

